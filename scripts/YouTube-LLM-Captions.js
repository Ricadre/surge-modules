/* YouTube LLM Captions 0.1.0. Backend is supplied by the installed module.
 * No embedded backend, credentials, telemetry or subtitle-content logging.
 * Backend API and privacy scope: docs/youtube-llm-captions.md.
 */
const VERSION = "0.1.0";
const PREFIX = "[YouTube LLM Captions " + VERSION + "]";

try {
  const args = parseArgs(typeof $argument !== "undefined" ? $argument : "");
  const settings = readSettings(args);
  const requestURL = typeof $request === "object" && $request ? $request.url : "";
  const result = !settings ? {} : typeof $response !== "undefined"
    ? handleResponse(requestURL, settings)
    : handleRequest(requestURL, settings);
  $done(result);
} catch (_) {
  console.log(PREFIX + " processing failed; original data kept");
  $done({});
}

function readSettings(args) {
  const backend = String(args.backend || "").trim().toLowerCase();
  const label = "[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?";
  const domain = new RegExp("^" + label + "(?:\\." + label + ")+$");
  if (backend.length > 253 || !domain.test(backend) ||
      /\.(invalid|localhost)$/.test(backend) ||
      backend === "youtube.com" || backend.endsWith(".youtube.com")) return null;
  const target = args.target || "zh-Hans";
  const dual = args.dual === undefined ? "true" : args.dual;
  if (!/^[a-z]{2,8}(?:-[a-z0-9]{1,8})*$/i.test(target) ||
      !["true", "false"].includes(dual)) return null;
  return { backend, target, dual };
}

function isYouTubeCaption(url) {
  return /^https?:\/\/(?:www|m)\.youtube\.com\/api\/timedtext\?[^#]*$/.test(String(url || ""));
}

function isBackendCaption(url, settings) {
  const prefix = "https://" + settings.backend + "/caption";
  return typeof url === "string" && (url === prefix || url.startsWith(prefix + "?")) &&
    !url.includes("#");
}

function handleRequest(url, settings) {
  if (!isYouTubeCaption(url)) return {};
  const language = queryValue(url, "tlang") || queryValue(url, "lang");
  if (isChinese(settings.target) && isChinese(language)) return {};
  return {
    url: "https://" + settings.backend + "/caption?src=" + encodeURIComponent(url) +
      "&target=" + encodeURIComponent(settings.target) + "&dual=" + settings.dual
  };
}

function handleResponse(url, settings) {
  if (!isYouTubeCaption(url) && !isBackendCaption(url, settings)) return {};
  const body = $response.body;
  if ($response.status !== 200 || typeof body !== "string" || !body) return {};
  const result = cleanCaption(body);
  return result.count ? { body: result.body } : {};
}

function cleanCaption(body) {
  let count = 0;
  let skipped = 0;
  if (body.trim().startsWith("{")) {
    const data = JSON.parse(body);
    if (!Array.isArray(data.events)) return { body, format: "unknown-json", count, skipped };
    for (const event of data.events) {
      if (!event || !Array.isArray(event.segs)) continue;
      // The proxy emits one text segment per cue; leave timed word streams intact.
      if (event.segs.length !== 1 || !event.segs[0] || typeof event.segs[0].utf8 !== "string") {
        skipped++;
        continue;
      }
      const clean = dedupePair(event.segs[0].utf8);
      if (clean !== null) {
        event.segs[0].utf8 = clean;
        count++;
      }
    }
    return { body: count ? JSON.stringify(data) : body, format: "json3", count, skipped };
  }
  if (!/<(?:timedtext|transcript)\b/.test(body)) return { body, format: "unknown", count, skipped };
  const output = body.replace(/<(p|text)\b([^>]*)>([\s\S]*?)<\/\1>/g, (whole, tag, attrs, inner) => {
    const raw = inner.replace(/<br\s*\/?\s*>/gi, "\n");
    // Only touch plain-text cues generated by the proxy, retaining the original XML envelope.
    if (/[<>]/.test(raw)) { skipped++; return whole; }
    const clean = dedupePair(decodeXml(raw));
    if (clean === null) return whole;
    count++;
    return `<${tag}${attrs}>${encodeXml(clean)}</${tag}>`;
  });
  return { body: output, format: "xml", count, skipped };
}

function dedupePair(text) {
  const lines = text.replace(/\r\n?/g, "\n").split("\n");
  if (lines.length !== 2 || !/[\u3400-\u9fff]/.test(lines[0])) return null;
  const normalize = (line) => line.replace(/\s+/g, " ").trim();
  if (normalize(lines[0]) !== normalize(lines[1])) return null;
  return lines[0];
}

function decodeXml(text) {
  return text.replace(/&#(x[0-9a-f]+|[0-9]+);|&(amp|lt|gt|quot|apos);/gi, (match, number, name) => {
    if (number) {
      const hex = number[0].toLowerCase() === "x";
      const value = parseInt(hex ? number.slice(1) : number, hex ? 16 : 10);
      if (value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff)) throw new Error("invalid XML entity");
      return String.fromCodePoint(value);
    }
    return ({ amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" })[name.toLowerCase()];
  });
}

function encodeXml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function isChinese(language) {
  return /^(zh|cmn|yue)(-|$)/i.test(String(language || "").trim().replace(/_/g, "-"));
}

function queryValue(url, name) {
  const match = String(url || "").match(new RegExp("[?&]" + name + "=([^&#]*)"));
  try { return match ? decodeURIComponent(match[1].replace(/\+/g, " ")) : ""; }
  catch { return ""; }
}

function parseArgs(str) {
  const out = {};
  String(str || "").split("&").forEach((pair) => {
    const index = pair.indexOf("=");
    if (index !== -1) out[pair.slice(0, index)] = decodeURIComponent(pair.slice(index + 1));
  });
  return out;
}
